import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { chromium } from "playwright-core";

const dir = fs.mkdtempSync(path.join(process.argv[2] ?? os.tmpdir(), "barista-file-ui-"));
process.env.CUA_RUN_DIR = dir; process.env.CUA_CONFIG = path.join(dir, "config.json");
const backend = path.join(dir, "backend.mjs"), record = path.join(dir, "input.json");
fs.writeFileSync(backend, `import fs from 'node:fs';let text='';process.stdin.on('data',x=>text+=x);process.stdin.on('end',()=>{fs.writeFileSync(${JSON.stringify(record)},text);console.log(JSON.stringify({type:'result',is_error:false,result:'Owned file received'}))});`);
fs.writeFileSync(process.env.CUA_CONFIG, JSON.stringify({web:{port:0},companion:{command:process.execPath,args:[backend]}}));
const { Pointers } = await import("../server/lib/pointer.mjs");
const { Companion } = await import("../server/lib/companion.mjs");
const { startWeb } = await import("../server/lib/web.mjs");
const { findExecutable } = await import("../server/lib/browser.mjs");
const pointers = new Pointers(); pointers.launch = () => {};
const companion = new Companion({pointers,native:{}}), first = companion.create({name:"First"});
const web = startWeb({engine:{running:false},native:{},hud:{},token:"fixture",status:async()=>({}),companion});
const {port} = await web.listen(), origin = `http://127.0.0.1:${port}`;
const browser = await chromium.launch({executablePath:findExecutable(),headless:true});
const page = await browser.newPage({viewport:{width:360,height:700}}), errors = [];
page.on("pageerror", e => errors.push(e.message));
const file = {name:"lesson.txt",mimeType:"text/plain",buffer:Buffer.from("Owned reference: CAFE-731")};
try {
  await page.goto(origin+"/companion?t=fixture"); await page.waitForFunction(()=>online);
  assert.equal(await page.getByRole("button",{name:"Attach files",exact:true}).count(),1,"Explicit file attachment control exists");
  await page.locator("#prompt").fill("Keep my question");
  const chooser = page.waitForEvent("filechooser"); await page.getByRole("button",{name:"Attach files",exact:true}).click();
  await (await chooser).setFiles(file); await page.waitForFunction(()=>current()?.files?.length===1&&!current().filesBusy);
  assert.equal(companion.get(first.id).messages.length,0); assert.equal(fs.existsSync(record),false);
  assert.equal(await page.locator("#prompt").inputValue(),"Keep my question");
  await page.locator("#fileContext").getByText("lesson.txt",{exact:true}).waitFor();
  assert.match(await page.locator("#fileContext").innerText(),/later model turns/i);
  await page.getByRole("button",{name:"Send question",exact:true}).click();
  await page.waitForFunction(()=>current()?.status==='done');
  const input = JSON.parse(fs.readFileSync(record,"utf8")); assert.match(input.message.content[1].text,/CAFE-731/);
  const remove = page.getByRole("button",{name:"Remove file lesson.txt",exact:true}); await remove.click();
  assert.equal(companion.get(first.id).files.length,1,"File removal needs confirmation");
  await page.getByRole("button",{name:"Confirm file removal lesson.txt",exact:true}).click();
  await page.waitForFunction(()=>current()?.files?.length===0);
  await page.evaluate(()=>{const data=new DataTransfer();data.items.add(new File(['Dropped reference'], 'drop.txt',{type:'text/plain'}));$('prompt').dispatchEvent(new DragEvent('drop',{dataTransfer:data,bubbles:true,cancelable:true}))});
  await page.waitForFunction(()=>current()?.files?.some(f=>f.name==='drop.txt'));
  await page.evaluate(()=>{const data=new DataTransfer();data.items.add(new File(['Pasted reference'], 'paste.txt',{type:'text/plain'}));$('prompt').dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}))});
  await page.waitForFunction(()=>current()?.files?.some(f=>f.name==='paste.txt'));
  await page.locator("#prompt").fill("Keep this after a rejected file");
  const bad = page.waitForEvent("filechooser"); await page.getByRole("button",{name:"Attach files",exact:true}).click();
  await (await bad).setFiles({name:"bad.exe",mimeType:"application/octet-stream",buffer:Buffer.from("not supported")});
  await page.locator("#error").waitFor({state:"visible"});
  assert.equal(await page.locator("#prompt").inputValue(),"Keep this after a rejected file");
  assert.equal(companion.get(first.id).files.length,2);
  await page.setViewportSize({width:320,height:700}); await page.emulateMedia({colorScheme:"dark",reducedMotion:"reduce"});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator("#app").screenshot({path:path.join(dir,"files-dark.png")});
  await page.reload(); await page.waitForFunction(()=>current()?.files?.length===2);
  const native = await browser.newPage(); native.on("pageerror",e=>errors.push(e.message));
  await native.addInitScript(()=>{window.nativeMessages=[];window.webkit={messageHandlers:{barista:{postMessage:m=>nativeMessages.push(m)}}}});
  await native.goto(origin+"/companion?t=fixture"); await native.waitForFunction(()=>online);
  await native.evaluate(()=>baristaRestoreDrafts({epoch:4,drafts:{}}));
  const binding = await native.evaluate(()=>baristaFilesPrepare({epoch:4,id:active,requestID:'owned-picker'}));
  assert(binding); assert.equal(binding.id,first.id);
  const other = companion.create({name:"Other"}); await native.waitForFunction(id=>state.sessions.some(s=>s.id===id),other.id);
  await native.evaluate(id=>chooseSession(id),other.id);
  assert.equal(await native.evaluate(({binding})=>baristaFilesAdd({...binding,files:[{name:'late.txt',data:btoa('Do not attach elsewhere')}]}),{binding}),false);
  assert.equal(companion.get(other.id).files.length,0); assert.equal(companion.get(first.id).files.length,2);
  const stale = await native.evaluate(()=>baristaFilesPrepare({epoch:3,id:active,requestID:'stale'})); assert.equal(stale,null);
  const valid = await native.evaluate(()=>baristaFilesPrepare({epoch:4,id:active,requestID:'valid'}));
  assert.equal(await native.evaluate(({valid})=>baristaFilesAdd({...valid,files:[{name:'native.txt',data:btoa('Native owned reference')}]}),{valid}),true);
  assert.equal(companion.get(other.id).files.length,1);
  assert.equal(await native.evaluate(()=>nativeMessages.filter(m=>m.action==='composerState').at(-1).fileCount),1);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,browserPicker:true,paste:true,drop:true,reload:true,nativeEpoch:true,conversationBinding:true,screenshots:dir}));
} finally { await browser.close(); companion.close(); pointers.shutdown(); web.server.closeAllConnections(); await new Promise(r=>web.server.close(r)); }
