import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { mock } from "node:test";
const dir=fs.mkdtempSync(path.join(process.argv[2]??os.tmpdir(),"cua-annotations-"));
process.env.CUA_RUN_DIR=dir;process.env.CUA_CONFIG=path.join(dir,"config.json");process.env.CUA_HUD_APP=path.join(dir,"missing.app");
const module=await import("../server/lib/pointer.mjs");
try {
 assert.equal(typeof module.cleanAnnotation,"function","annotations have a bounded public contract");
 const {Pointers,cleanAnnotation}=module;
 assert.equal(cleanAnnotation({kind:"circle",rect:{x:-400,y:80,w:180,h:90}}).kind,"circle");
 assert.throws(()=>cleanAnnotation({kind:"draw",points:[[0,0],[Infinity,2]]}),/finite/);
 assert.throws(()=>cleanAnnotation({kind:"draw",points:Array(513).fill([1,2])}),/512/);
 assert.throws(()=>cleanAnnotation({kind:"script",rect:{x:1,y:1,w:2,h:2}}),/kind/);
 const p=new Pointers(), a=p.session({name:"Andy"}), b=p.session({name:"Other"});
 p.move(b,{screen:[10,20]});
 const circle=p.annotate(a,{kind:"circle",rect:{x:-400,y:80,w:180,h:90},label:"This control"});
 p.annotate(a,{kind:"arrow",points:[[-300,90],[-100,150]],label:"Next"});
 assert.equal(p.snapshot().cursors[a].annotations.length,2,"marks persist while the pointer moves");
 assert.equal(p.snapshot().cursors[a].annotations[0].id,circle);
 for(let i=0;i<20;i++)p.annotate(a,{kind:"draw",points:[[i,0],[i,30]]});
 assert.equal(p.snapshot().cursors[a].annotations.length,12,"history is bounded");
 p.hide(a);assert.equal(p.snapshot().cursors[a],undefined);assert.ok(p.snapshot().cursors[b]);
 let finished=0;p.demo({bounds:{x:-1920,y:200,w:1920,h:1000},start:[-1000,500]},()=>finished++);
 assert.ok(p.snapshot().cursors[b],"demo does not clear another agent");
 p.stopDemo();assert.equal(finished,1);assert.deepEqual(Object.keys(p.snapshot().cursors),[b]);
 p.stopDemo();assert.equal(finished,1,"demo cleanup is idempotent");
 mock.timers.enable({apis:['setTimeout','Date']});
 p.demo({bounds:{x:0,y:0,w:1200,h:800},start:[600,400]},()=>finished++);
 mock.timers.tick(6500);
 const demo=Object.values(p.snapshot().cursors).find(c=>c.name==='Andy · Local demo');
 assert.equal(demo.state,'done','demo includes an adaptive idle phase');
 assert.equal(demo.annotations.length,4,'idle return keeps all four marks');
 mock.timers.tick(6500);
 assert.equal(finished,2,'demo automatically removes its cursor');
 assert.deepEqual(Object.keys(p.snapshot().cursors),[b]);mock.timers.reset();
 p.shutdown();console.log("PASS annotation validation, persistence, isolation, and demo cleanup");
} finally {fs.rmSync(dir,{recursive:true,force:true})}
